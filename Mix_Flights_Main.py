summary = []
for ev in run_trace.get("destinations", []):
    prices = (ev.get("prices_seen") or {}).get("values") or []
    if not prices:
        summary.append({
            "destination": ev.get("destination"),
            "count": 0,
            "min": None,
            "avg": None,
            "max": None,
            "currency": (ev.get("prices_seen") or {}).get("currency")
        })
        continue
    mn = min(prices)
    mx = max(prices)
    avg = sum(prices) / len(prices)
    summary.append({
        "destination": ev.get("destination"),
        "count": len(prices),
        "min": round(mn, 2),
        "avg": round(avg, 2),
        "max": round(mx, 2),
        "currency": (ev.get("prices_seen") or {}).get("currency")
    })

logger.info("----- Price Summary (min/avg/max) -----")
