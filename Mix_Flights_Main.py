def _setup_logger(level=logging.INFO):  # [ADDED]
    logger = logging.getLogger("travel")
    logger.handlers.clear()
    logger.setLevel(level)
    ch = logging.StreamHandler(sys.stdout)
    ch.setLevel(level)
    ch.setFormatter(logging.Formatter("%(levelname)s %(message)s"))
    logger.addHandler(ch)
    return logger

def _write_trace_file(trace_obj, path="trace.json"):  # [ADDED]
    with open(path, "w", encoding="utf-8") as f:
        json.dump(trace_obj, f, indent=2, sort_keys=True, ensure_ascii=False)

# [ADDED] Quick SMTP diagnostics to see which path works on this network
def _smtp_probe(host="smtp.gmail.com", timeout=8):
    results = {}
    # STARTTLS on 587
    try:
        with smtplib.SMTP(host, 587, timeout=timeout) as s:
            s.ehlo()
            s.starttls(context=ssl.create_default_context())
            s.ehlo()
            results["587_STARTTLS"] = "OK"
    except Exception as e:
        results["587_STARTTLS"] = f"FAIL: {e!r}"
    # Implicit SSL on 465
    try:
        with smtplib.SMTP_SSL(host, 465, timeout=timeout, context=ssl.create_default_context()) as s:
            s.ehlo()
            results["465_SSL"] = "OK"
    except Exception as e:
        results["465_SSL"] = f"FAIL: {e!r}"
    return results

