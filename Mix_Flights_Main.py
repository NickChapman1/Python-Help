def evaluate_price_drop(
    sheet_row: dict,
    cheapest_offer: Optional[dict],
) -> Tuple[bool, dict]:
    """
    Returns (should_notify, payload).
    payload has: subject, body_text, body_html.
    """
    city = (sheet_row.get("city") or "").strip()
    # Your sheet may use 'lowestPrice' (100 Days of Code project) – keep both just in case
    sheet_price_str = (sheet_row.get("lowestPrice") or sheet_row.get("lowest_price") or "").strip()
    try:
        sheet_price = float(sheet_price_str) if sheet_price_str else None
    except ValueError:
        sheet_price = None

    if not cheapest_offer:
        return (False, {})

    price = (cheapest_offer.get("price") or {}).get("total")
    currency = (cheapest_offer.get("price") or {}).get("currency") or "USD"
    try:
        current = float(price) if price is not None else None
    except ValueError:
        current = None

    if current is None or sheet_price is None:
        return (False, {})

    # Only alert when the new price is strictly lower
    if current >= sheet_price:
        return (False, {})

    drop_abs = sheet_price - current
    subject = f"Lower price found: {city} now {currency} {current:.2f} (was {sheet_price:.2f})"

    body_text = (
        f"Good news!\n\n"
        f"Destination: {city}\n"
        f"Lower price found: {currency} {current:.2f}\n"
        f"Your baseline price: {currency} {sheet_price:.2f}\n"
        f"Difference: {currency} {drop_abs:.2f}\n\n"
        f"This email was auto-generated by Flight Deals."
    )

    payload = {
        "subject": subject,
        "body_text": body_text,
    }
    return (True, payload)

